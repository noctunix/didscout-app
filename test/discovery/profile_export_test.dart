import 'package:flutter_test/flutter_test.dart';

import 'package:didscout_app/discovery/discovery_state.dart';
import 'package:didscout_app/discovery/profile_export.dart';

/// Minimal line-based TOML check -- just enough to confirm the draft is
/// well-formed and carries the fields the schema requires, without
/// pulling in a TOML parsing dependency for one test.
class _ParsedToml {
  final Map<String, String> topLevel = {};
  final List<Map<String, String>> modules = [];
  final List<Map<String, String>> moduleDids = [];

  static _ParsedToml parse(String toml) {
    final result = _ParsedToml();
    Map<String, String>? current;
    for (final rawLine in toml.split('\n')) {
      final line = rawLine.trim();
      if (line.isEmpty) continue;
      if (line == '[[sources]]') {
        current = null; // not asserted on in this test
        continue;
      }
      if (line == '[[modules]]') {
        current = {};
        result.modules.add(current);
        continue;
      }
      if (line == '[[modules.dids]]') {
        current = {};
        result.moduleDids.add(current);
        continue;
      }
      final match = RegExp(r'^([A-Za-z]+)\s*=\s*(.+)$').firstMatch(line);
      if (match == null) continue;
      final key = match.group(1)!;
      final rawValue = match.group(2)!;
      final value = rawValue.startsWith('"')
          ? rawValue.substring(1, rawValue.length - 1)
          : rawValue;
      (current ?? result.topLevel)[key] = value;
    }
    return result;
  }
}

void main() {
  test('exports a parseable draft with every known ECU and hit', () {
    final state = DiscoveryState();
    state.ecus['ecus11-700'] = EcuInfo(
      requestHeader: '700',
      responseHeader: '708',
      protocol: 6,
      discovered: {'2A04', '2A15'},
    );
    state.ecus['ecus29-04'] = EcuInfo(
      requestHeader: '18DA04F1',
      responseHeader: '18DAF104',
      protocol: 7,
    );

    final toml = exportProfileDraft(
      state,
      id: 'draft-vehicle',
      name: 'Draft vehicle',
      description: 'Autogenerated discovery draft.',
      vehicles: ['Test vehicle'],
    );

    final parsed = _ParsedToml.parse(toml);
    expect(parsed.topLevel['schema'], '1');
    expect(parsed.topLevel['id'], 'draft-vehicle');
    expect(parsed.topLevel['protocol'], '6');

    expect(parsed.modules.length, 2);
    final gateway = parsed.modules.firstWhere((m) => m['id'] == 'ecus11-700');
    expect(gateway['request'], '700');
    expect(gateway['response'], '708');
    expect(
      gateway.containsKey('protocol'),
      isFalse,
    ); // 6 is the default, omitted

    final other = parsed.modules.firstWhere((m) => m['id'] == 'ecus29-04');
    expect(other['protocol'], '7');

    expect(parsed.moduleDids.length, 2);
    for (final did in parsed.moduleDids) {
      expect(did['status'], 'unverified');
      expect(did['poll'], 'survey');
      expect(did['interval'], isNotNull);
      expect(did.containsKey('name'), isFalse);
    }
    expect(parsed.moduleDids.map((d) => d['did']).toSet(), {'2A04', '2A15'});
  });

  test('a known ECU with no hits yet still gets a module entry', () {
    final state = DiscoveryState();
    state.ecus['ecus11-7a1'] = EcuInfo(
      requestHeader: '7A1',
      responseHeader: '7A9',
      protocol: 6,
    );

    final toml = exportProfileDraft(
      state,
      id: 'draft',
      name: 'Draft',
      description: 'Draft.',
    );
    final parsed = _ParsedToml.parse(toml);
    expect(parsed.modules.single['id'], 'ecus11-7a1');
    expect(parsed.moduleDids, isEmpty);
  });
}
